import Foundation

public enum ShortcutError: Error, Equatable {
    case invalidName(String)
    case recipeMissing(String)
    case emptyProgram
}

/// Everything a generated `.app` needs to launch one program later.
public struct ShortcutSpec: Sendable {
    public var name: String
    public var recipe: URL
    /// Program and arguments exactly as passed to Wine.
    public var program: [String]
    /// Path of the WinDA launcher executable the shortcut calls.
    public var launcher: URL
    public var manifestsDirectory: URL
    public var engineRoot: URL
    public var bottlesRoot: URL
    /// Where the shortcut writes its output.
    public var logDirectory: URL
    /// Shared winetricks download cache; optional.
    public var cacheDirectory: URL?

    public init(name: String, recipe: URL, program: [String], launcher: URL, manifestsDirectory: URL,
                engineRoot: URL, bottlesRoot: URL, logDirectory: URL, cacheDirectory: URL? = nil) {
        self.name = name
        self.recipe = recipe
        self.program = program
        self.launcher = launcher
        self.manifestsDirectory = manifestsDirectory
        self.engineRoot = engineRoot
        self.bottlesRoot = bottlesRoot
        self.logDirectory = logDirectory
        self.cacheDirectory = cacheDirectory
    }
}

/// Writes a minimal macOS app bundle whose executable is a shell script that
/// calls the launcher. The recipe is copied into the bundle, so the shortcut
/// keeps working if the original file moves.
public enum ShortcutGenerator {
    public static func sanitize(_ name: String) throws -> String {
        let cleaned = name.replacingOccurrences(of: #"[\/:\\\u0000-\u001f]"#, with: "-", options: .regularExpression)
            .trimmingCharacters(in: .whitespaces)
        guard !cleaned.isEmpty, !cleaned.hasPrefix("."), cleaned.count <= 100 else { throw ShortcutError.invalidName(name) }
        return cleaned
    }

    /// Single-quote a string for /bin/sh.
    public static func shellQuote(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    static func slug(_ name: String) -> String {
        let s = name.lowercased().replacingOccurrences(of: "[^a-z0-9]+", with: "-", options: .regularExpression)
            .trimmingCharacters(in: CharacterSet(charactersIn: "-"))
        return s.isEmpty ? "app" : s
    }

    static func script(spec: ShortcutSpec, recipe: String, slug: String) -> String {
        let q = shellQuote
        let log = spec.logDirectory.appendingPathComponent("\(slug).log").path
        let program = spec.program.map(q).joined(separator: " ")
        return """
        #!/bin/sh
        # Generated by WinDA. Edit by regenerating the shortcut.
        DIR="$(cd "$(dirname "$0")/.." && pwd)"
        mkdir -p \(q(spec.logDirectory.path))
        exec \(q(spec.launcher.path)) launch \\
          --recipe "$DIR/Resources/\(recipe)" \\
          --manifests \(q(spec.manifestsDirectory.path)) \\
          --engine-root \(q(spec.engineRoot.path)) \\
          --bottles \(q(spec.bottlesRoot.path)) \\
        \(spec.cacheDirectory.map { "  --cache \(q($0.path)) \\\n" } ?? "")  -- \(program) >> \(q(log)) 2>&1

        """
    }

    /// - Returns: the created `<name>.app` inside `directory`.
    @discardableResult
    public static func create(_ spec: ShortcutSpec, in directory: URL) throws -> URL {
        let name = try sanitize(spec.name)
        guard !spec.program.isEmpty else { throw ShortcutError.emptyProgram }
        let fm = FileManager.default
        guard fm.fileExists(atPath: spec.recipe.path) else { throw ShortcutError.recipeMissing(spec.recipe.path) }

        let slug = slug(name)
        let app = directory.appendingPathComponent("\(name).app")
        if fm.fileExists(atPath: app.path) { try fm.removeItem(at: app) }
        let macOS = app.appendingPathComponent("Contents/MacOS")
        let resources = app.appendingPathComponent("Contents/Resources")
        try fm.createDirectory(at: macOS, withIntermediateDirectories: true)
        try fm.createDirectory(at: resources, withIntermediateDirectories: true)

        try fm.copyItem(at: spec.recipe, to: resources.appendingPathComponent("recipe.json"))

        let exe = macOS.appendingPathComponent("launch")
        try Data(script(spec: spec, recipe: "recipe.json", slug: slug).utf8).write(to: exe)
        try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: exe.path)

        let plist: [String: Any] = [
            "CFBundleName": name,
            "CFBundleDisplayName": name,
            "CFBundleIdentifier": "app.winda.shortcut.\(slug)",
            "CFBundleExecutable": "launch",
            "CFBundlePackageType": "APPL",
            "CFBundleShortVersionString": "1.0",
            "CFBundleVersion": "1",
            "LSMinimumSystemVersion": "15.0",
            "NSHighResolutionCapable": true,
        ]
        let data = try PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0)
        try data.write(to: app.appendingPathComponent("Contents/Info.plist"))
        return app
    }
}
